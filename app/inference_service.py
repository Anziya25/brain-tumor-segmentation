
import functools
from pathlib import Path

import nibabel as nib
import numpy as np
import torch
from monai.inferers import sliding_window_inference

PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODEL_DIR = PROJECT_ROOT / "models" / "unetr-brats"
FT_CHECKPOINT_PATH = PROJECT_ROOT / "models" / "finetuned_unetr.pth"

import sys

sys.path.insert(0, str(MODEL_DIR))

from app.preprocessing import get_inference_transforms

PATCH_SIZE = (128, 128, 128)
SW_BATCH_SIZE = 1


class SegmentationService:
    def __init__(self):
        # Import model code only when inference is actually requested.
        from inference import load_model

        if not MODEL_DIR.is_dir():
            raise FileNotFoundError(f"Model directory not found: {MODEL_DIR}")

        baseline_weights = MODEL_DIR / "pytorch_model.bin"
        if not baseline_weights.is_file():
            raise FileNotFoundError(
                f"Pretrained model weights not found: {baseline_weights}"
            )

        if not FT_CHECKPOINT_PATH.is_file():
            raise FileNotFoundError(
                f"Fine-tuned checkpoint not found: {FT_CHECKPOINT_PATH}"
            )

        self.device = torch.device(
            "cuda" if torch.cuda.is_available() else "cpu"
        )

        self.model, self.metadata = load_model(str(baseline_weights))

        # Only load checkpoints generated by your trusted training pipeline.
        checkpoint = torch.load(
            FT_CHECKPOINT_PATH,
            map_location="cpu",
            weights_only=False,
        )

        if "model_state_dict" not in checkpoint:
            raise KeyError(
                "Fine-tuned checkpoint is missing 'model_state_dict'."
            )

        self.model.load_state_dict(checkpoint["model_state_dict"])
        self.model.to(self.device)
        self.model.eval()

        self.model_val_dice = checkpoint.get(
            "val_dice_mean",
            self.metadata.get("val_dice_mean", 0.0),
        )

        self.transforms = get_inference_transforms()

        print(
            f"Model loaded on {self.device}. "
            f"Fine-tuned validation Dice: {self.model_val_dice}"
        )

    def predict(
        self,
        t1_path,
        t1ce_path,
        t2_path,
        flair_path,
        output_mask_path,
    ):
        # Validate input files before preprocessing.
        input_paths = {
            "t1": t1_path,
            "t1ce": t1ce_path,
            "t2": t2_path,
            "flair": flair_path,
        }

        for modality, path in input_paths.items():
            if not Path(path).is_file():
                raise FileNotFoundError(
                    f"{modality} MRI file not found: {path}"
                )

        sample = dict(input_paths)
        processed = self.transforms(sample)

        image_meta = processed["image"]
        image = image_meta.unsqueeze(0).to(self.device)

        with torch.inference_mode():
            probs = sliding_window_inference(
                inputs=image,
                roi_size=PATCH_SIZE,
                sw_batch_size=SW_BATCH_SIZE,
                predictor=lambda x: torch.sigmoid(self.model(x)),
                overlap=0.25,
            )

        # Expected channel order: [ET, TC, WT].
        pred_binary = (probs > 0.5).to(torch.uint8).cpu().numpy()[0]

        if pred_binary.ndim != 4 or pred_binary.shape[0] != 3:
            raise ValueError(
                "Expected model predictions with shape [3, D, H, W]; "
                f"received {pred_binary.shape}."
            )

        et, tc, wt = pred_binary[0], pred_binary[1], pred_binary[2]

        # Convert nested regions to a single label map.
        # 0 = background, 2 = WT-only, 1 = TC-only, 4 = ET.
        combined = np.zeros(et.shape, dtype=np.uint8)
        combined[wt > 0] = 2
        combined[tc > 0] = 1
        combined[et > 0] = 4

        # Use the affine of the actual preprocessed image grid.
        # Do not apply the original T1 affine to a resampled prediction.
        affine_value = getattr(image_meta, "affine", None)

        if affine_value is None:
            raise RuntimeError(
                "Preprocessing did not preserve image affine metadata. "
                "Cannot safely save the segmentation in world coordinates."
            )

        if torch.is_tensor(affine_value):
            affine = affine_value.detach().cpu().numpy()
        else:
            affine = np.asarray(affine_value)

        if affine.ndim == 3:
            affine = affine[0]

        if affine.shape != (4, 4):
            raise ValueError(
                f"Expected a 4x4 image affine, received {affine.shape}."
            )

        # Voxel volume in mm³, calculated from the affine.
        voxel_volume_mm3 = abs(float(np.linalg.det(affine[:3, :3])))

        if not np.isfinite(voxel_volume_mm3) or voxel_volume_mm3 <= 0:
            raise ValueError("Invalid voxel volume from image affine.")

        voxel_volume_ml = voxel_volume_mm3 / 1000.0

        output_path = Path(output_mask_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)

        output_img = nib.Nifti1Image(combined, affine=affine)
        nib.save(output_img, str(output_path))

        return {
            "enhancing_tumor_volume_ml": round(
                float(et.sum()) * voxel_volume_ml, 3
            ),
            "tumor_core_volume_ml": round(
                float(tc.sum()) * voxel_volume_ml, 3
            ),
            "whole_tumor_volume_ml": round(
                float(wt.sum()) * voxel_volume_ml, 3
            ),
            "mask_path": str(output_path),
        }


# Lazy singleton: loading the service requires the actual model files.
@functools.lru_cache(maxsize=1)
def get_segmentation_service():
    return SegmentationService()
